/* Enunciado do exercício:

- Crie uma string "Java" e use o charAt(0) para exibir o primeiro caractere da palavra. */

package exercise41;

/**
 *
 * @author andrelauterjung
 */
public class Main {
    
    public static void main(String[] args) {
        
        String palavra = "Java";
        
        System.out.println("\n===============================================");
        System.out.println("Palavra: "+palavra);
        System.out.println("Caracter na posicão 0: "+palavra.charAt(0));

        System.out.println("\n===============================================");
        System.out.println("Programa encerrado!");
        System.out.println("===============================================");
    }
}

/* Enunciado do exercício:

- Crie uma string contendo um hífen ("-") e utilize o método repeat(20) para imprimi-la repetida 20 vezes, formando
uma linha divisória na tela. */

package exercise45;

/**
 *
 * @author andrelauterjung
 */
public class Main {
    
    public static void main(String[] args) {
        
        String hifen = "-";
        
        System.out.println("\n===============================================");
        
        System.out.println("\nResultado: "+hifen.repeat(20));
        System.out.println("\n===============================================");
        System.out.println("Programa encerrado!");
        System.out.println("===============================================");
    }
}
